import { Component, OnInit, inject, signal } from '@angular/core';
import { HttpErrorResponse } from '@angular/common/http';
import {
  FormBuilder,
  ReactiveFormsModule,
  Validators
} from '@angular/forms';
import { ActivatedRoute, Router, RouterLink } from '@angular/router';
import { Observable } from 'rxjs';

import { AbsenceDeductionRuleService } from '../../../Core/services/absence-deduction-rule';

@Component({
  selector: 'app-absence-rule-form',
  standalone: true,
  imports: [ReactiveFormsModule, RouterLink],
  templateUrl: './absence-rule-form.html',
  styleUrl: './absence-rule-form.css'
})
export class AbsenceRuleForm implements OnInit {
  private readonly fb = inject(FormBuilder);
  private readonly ruleService = inject(AbsenceDeductionRuleService);
  private readonly route = inject(ActivatedRoute);
  private readonly router = inject(Router);

  isEditMode = this.route.snapshot.paramMap.has('id');
  ruleId = Number(this.route.snapshot.paramMap.get('id'));

  rowVersion = '';

  loading = signal(false);
  saving = signal(false);
  errorMessage = signal('');

  form = this.fb.nonNullable.group({
    minimumDays: [
      0,
      [
        Validators.required,
        Validators.min(0),
        Validators.pattern(/^\d+$/)
      ]
    ],
    percentage: [
      0,
      [
        Validators.required,
        Validators.min(0),
        Validators.max(100)
      ]
    ],
    type: ['']
  });

  ngOnInit(): void {
    // Type is always generated by the backend.
    this.form.controls.type.disable();

    if (this.isEditMode) {
      this.loadRule();
    }
  }

  loadRule(): void {
    this.loading.set(true);
    this.errorMessage.set('');

    this.ruleService.getAll().subscribe({
      next: rules => {
        const rule = rules.find(item => item.id === this.ruleId);

        if (!rule) {
          this.errorMessage.set('Absence deduction rule not found.');
          this.loading.set(false);
          return;
        }

        this.form.patchValue({
          minimumDays: rule.minimumDays,
          percentage: rule.percentage,
          type: rule.type
        });

        this.rowVersion = rule.rowVersion;

        // MinimumDays cannot be changed after creation.
        this.form.controls.minimumDays.disable();

        this.loading.set(false);
      },
      error: (error: HttpErrorResponse) => {
        this.errorMessage.set(
          error.error?.detail || 'Failed to load absence deduction rule.'
        );
        this.loading.set(false);
      }
    });
  }

  save(): void {
    if (this.form.invalid || this.loading() || this.saving()) {
      this.form.markAllAsTouched();
      return;
    }

    const values = this.form.getRawValue();

    this.saving.set(true);
    this.errorMessage.set('');

    const request: Observable<unknown> = this.isEditMode
      ? this.ruleService.update({
          id: this.ruleId,
          percentage: Number(values.percentage),
          rowVersion: this.rowVersion
        })
      : this.ruleService.create({
          minimumDays: Number(values.minimumDays),
          percentage: Number(values.percentage)
        });

    request.subscribe({
      next: () => {
        this.router.navigate(['/absence-rules']);
      },
      error: (error: HttpErrorResponse) => {
        this.errorMessage.set(
          error.error?.detail || 'Failed to save absence deduction rule.'
        );
        this.saving.set(false);
      }
    });
  }
}